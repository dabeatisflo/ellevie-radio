const {
  AndroidConfig,
  createRunOncePlugin,
  withAndroidManifest,
  withAppBuildGradle,
  withDangerousMod,
} = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const PLUGIN_NAME = 'ellevie-android-auto';
const PLUGIN_VERSION = '1.0.0';
const MEDIA3_VERSION = '1.9.0';
const SERVICE_NAME = '.automotive.EllevieMediaService';

function upsertMetaData(application, name, resource) {
  application['meta-data'] = application['meta-data'] || [];
  const existing = application['meta-data'].find((entry) => entry.$?.['android:name'] === name);
  if (existing) {
    existing.$['android:resource'] = resource;
    delete existing.$['android:value'];
  } else {
    application['meta-data'].push({ $: { 'android:name': name, 'android:resource': resource } });
  }
}

function withEllevieAndroidManifest(config) {
  return withAndroidManifest(config, (next) => {
    AndroidConfig.Permissions.addPermission(next.modResults, 'android.permission.WAKE_LOCK');
    const application = next.modResults.manifest.application?.[0];
    if (!application) throw new Error('Android application manifest is missing.');
    application.service = (application.service || []).filter(
      (service) => service.$?.['android:name'] !== SERVICE_NAME,
    );
    application.service.push({
      $: {
        'android:name': SERVICE_NAME,
        'android:exported': 'true',
        'android:foregroundServiceType': 'mediaPlayback',
        'android:label': 'ELLEVIE',
      },
      'intent-filter': [{ action: [
        { $: { 'android:name': 'androidx.media3.session.MediaLibraryService' } },
        { $: { 'android:name': 'android.media.browse.MediaBrowserService' } },
      ] }],
    });
    upsertMetaData(application, 'com.google.android.gms.car.application', '@xml/automotive_app_desc');
    upsertMetaData(application, 'androidx.car.app.TintableAttributionIcon', '@drawable/ellevie_car_attribution_icon');
    return next;
  });
}

function withEllevieMedia3Dependencies(config) {
  return withAppBuildGradle(config, (next) => {
    if (next.modResults.language !== 'groovy') throw new Error('ELLEVIE Android Auto expects Groovy.');
    const marker = '// @generated by ellevie-android-auto';
    if (!next.modResults.contents.includes(marker)) {
      next.modResults.contents = next.modResults.contents.replace(
        /dependencies\s*\{/,
        `dependencies {\n    ${marker}\n    implementation "androidx.media3:media3-exoplayer:${MEDIA3_VERSION}"\n    implementation "androidx.media3:media3-session:${MEDIA3_VERSION}"`,
      );
    }
    return next;
  });
}

function writeFile(filePath, contents) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

function withEllevieAndroidSources(config) {
  return withDangerousMod(config, ['android', async (next) => {
    const packageName = next.android?.package;
    if (!packageName) throw new Error('Set expo.android.package before enabling Android Auto.');
    const androidRoot = next.modRequest.platformProjectRoot;
    const sourceRoot = path.join(androidRoot, 'app', 'src', 'main', 'java', ...packageName.split('.'), 'automotive');
    const resourcesRoot = path.join(androidRoot, 'app', 'src', 'main', 'res');
    writeFile(path.join(sourceRoot, 'EllevieMediaService.kt'), mediaServiceSource.replaceAll('__PACKAGE__', packageName));
    writeFile(path.join(resourcesRoot, 'xml', 'automotive_app_desc.xml'), automotiveDescriptor);
    writeFile(path.join(resourcesRoot, 'drawable', 'ellevie_car_attribution_icon.xml'), attributionIcon);
    return next;
  }]);
}

function withAndroidAuto(config) {
  config = withEllevieAndroidManifest(config);
  config = withEllevieMedia3Dependencies(config);
  config = withEllevieAndroidSources(config);
  return config;
}

const mediaServiceSource = `package __PACKAGE__.automotive

import android.net.Uri
import androidx.media3.common.AudioAttributes
import androidx.media3.common.C
import androidx.media3.common.MediaItem
import androidx.media3.common.MediaMetadata
import androidx.media3.exoplayer.ExoPlayer
import androidx.media3.session.LibraryResult
import androidx.media3.session.MediaLibraryService
import androidx.media3.session.MediaLibraryService.LibraryParams
import androidx.media3.session.MediaLibraryService.MediaLibrarySession
import androidx.media3.session.MediaSession
import com.google.common.collect.ImmutableList
import com.google.common.util.concurrent.Futures
import com.google.common.util.concurrent.ListenableFuture

@androidx.annotation.OptIn(androidx.media3.common.util.UnstableApi::class)
class EllevieMediaService : MediaLibraryService() {
  companion object {
    private const val ROOT_ID = "ellevie-root"
    private const val LIVE_ID = "ellevie-live"
    private const val STREAM_URL = "https://stream.zeno.fm/5ct6gd3f0rhvv"
    private const val ARTWORK_URL = "https://studio.ellevie.fr/iphone/assets/icon-512.png"
  }
  private var librarySession: MediaLibrarySession? = null
  private val rootItem by lazy { MediaItem.Builder().setMediaId(ROOT_ID).setMediaMetadata(
    MediaMetadata.Builder().setTitle("ELLEVIE").setIsBrowsable(true).setIsPlayable(false).build()
  ).build() }
  private val liveItem by lazy { MediaItem.Builder().setMediaId(LIVE_ID).setUri(STREAM_URL).setMediaMetadata(
    MediaMetadata.Builder().setTitle("ELLEVIE Live").setArtist("La radio feel good")
      .setAlbumTitle("Lady's First").setArtworkUri(Uri.parse(ARTWORK_URL))
      .setMediaType(MediaMetadata.MEDIA_TYPE_RADIO_STATION).setIsBrowsable(false).setIsPlayable(true).build()
  ).build() }
  private val callback = object : MediaLibrarySession.Callback {
    override fun onGetLibraryRoot(session: MediaLibrarySession, browser: MediaSession.ControllerInfo, params: LibraryParams?) =
      Futures.immediateFuture(LibraryResult.ofItem(rootItem, params))
    override fun onGetItem(session: MediaLibrarySession, browser: MediaSession.ControllerInfo, mediaId: String) =
      Futures.immediateFuture(if (mediaId == ROOT_ID) LibraryResult.ofItem(rootItem, null) else if (mediaId == LIVE_ID) LibraryResult.ofItem(liveItem, null) else LibraryResult.ofError(LibraryResult.RESULT_ERROR_BAD_VALUE))
    override fun onGetChildren(session: MediaLibrarySession, browser: MediaSession.ControllerInfo, parentId: String, page: Int, pageSize: Int, params: LibraryParams?): ListenableFuture<LibraryResult<ImmutableList<MediaItem>>> =
      Futures.immediateFuture(LibraryResult.ofItemList(if (parentId == ROOT_ID && page == 0) listOf(liveItem) else emptyList(), params))
    override fun onSearch(session: MediaLibrarySession, browser: MediaSession.ControllerInfo, query: String, params: LibraryParams?): ListenableFuture<LibraryResult<Void>> {
      session.notifySearchResultChanged(browser, query, 1, params)
      return Futures.immediateFuture(LibraryResult.ofVoid(params))
    }
    override fun onGetSearchResult(session: MediaLibrarySession, browser: MediaSession.ControllerInfo, query: String, page: Int, pageSize: Int, params: LibraryParams?): ListenableFuture<LibraryResult<ImmutableList<MediaItem>>> =
      Futures.immediateFuture(LibraryResult.ofItemList(if (page == 0) listOf(liveItem) else emptyList(), params))
    override fun onAddMediaItems(mediaSession: MediaSession, controller: MediaSession.ControllerInfo, mediaItems: List<MediaItem>): ListenableFuture<List<MediaItem>> =
      Futures.immediateFuture(mediaItems.map { liveItem })
  }
  override fun onCreate() {
    super.onCreate()
    val player = ExoPlayer.Builder(this).setAudioAttributes(
      AudioAttributes.Builder().setContentType(C.AUDIO_CONTENT_TYPE_MUSIC).setUsage(C.USAGE_MEDIA).build(), true
    ).setHandleAudioBecomingNoisy(true).build()
    librarySession = MediaLibrarySession.Builder(this, player, callback).setId("ellevie-android-auto").build()
  }
  override fun onGetSession(controllerInfo: MediaSession.ControllerInfo): MediaLibrarySession? = librarySession
  override fun onDestroy() {
    librarySession?.run { player.release(); release() }
    librarySession = null
    super.onDestroy()
  }
}
`;

